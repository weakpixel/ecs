// Command gen generates the arity-1..16 generic API family (ComponentsN,
// NewEntityN, NewViewN/ViewN) into zz_gen_generic-api.go at the module root,
// plus a round-trip smoke test per arity into zz_gen_generic-api_test.go.
//
// It is invoked by the //go:generate directive in generic.go, as part of
// `go generate ./...` / `make all`. It uses only the standard library: the
// arities are pure data, not derived from parsed Go source, so there is no
// package-loading step.
package main

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"text/template"
)

//go:embed templates/*.tpl
var templatesFS embed.FS

const mainOutName = "zz_gen_generic-api.go"
const testOutName = "zz_gen_generic-api_test.go"

const mainHeader = `// Code generated by internal/gen; DO NOT EDIT.

package ecs

import (
	"iter"

	"github.com/weakpixel/ecs/internal/storage"
)
`

const testHeader = `// Code generated by internal/gen; DO NOT EDIT.

package ecs_test

import (
	"testing"

	"github.com/weakpixel/ecs"
)
`

func main() {
	if err := run(mainOutName, testOutName); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// run renders both generated files and writes them to mainPath/testPath,
// each only if its content changed. Called directly (with temp paths) by
// the self-check test, and by main (with the real output paths, relative to
// the module root since go:generate runs there, in generic.go's directory).
func run(mainPath, testPath string) error {
	arities := buildArities()

	mainSrc, err := render(arities)
	if err != nil {
		return fmt.Errorf("render %s: %w", mainOutName, err)
	}
	if err := writeFile(mainPath, mainSrc); err != nil {
		return err
	}

	testSrc, err := renderTest(arities)
	if err != nil {
		return fmt.Errorf("render %s: %w", testOutName, err)
	}
	return writeFile(testPath, testSrc)
}

// render produces zz_gen_generic-api.go: ComponentsN (N >= 2),
// NewEntityN and NewViewN/ViewN for every arity, in order.
func render(arities []arity) ([]byte, error) {
	tpl, err := template.ParseFS(templatesFS, "templates/*.tpl")
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	buf.WriteString(mainHeader)
	for _, a := range arities {
		for _, name := range []string{"components", "newEntity", "view"} {
			if err := tpl.ExecuteTemplate(&buf, name, a); err != nil {
				return nil, fmt.Errorf("arity %d, template %q: %w", a.N, name, err)
			}
		}
	}
	return format.Source(buf.Bytes())
}

// renderTest produces zz_gen_generic-api_test.go: one smoke test per
// arity.
func renderTest(arities []arity) ([]byte, error) {
	tpl, err := template.ParseFS(templatesFS, "templates/*.tpl")
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	buf.WriteString(testHeader)
	for _, a := range arities {
		if err := tpl.ExecuteTemplate(&buf, "test", a); err != nil {
			return nil, fmt.Errorf("arity %d, template \"test\": %w", a.N, err)
		}
	}
	return format.Source(buf.Bytes())
}

// writeFile writes content to path unless the file already has it, so
// `go generate` doesn't touch mtimes (and git doesn't see a no-op diff)
// when nothing changed.
func writeFile(path string, content []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, content) {
		return nil
	}
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	return os.WriteFile(path, content, 0o644)
}
